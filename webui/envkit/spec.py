# -*- coding: utf-8 -*-
"""spec.py —— 环境清单与环境目录布局的唯一真源
================================================================
换电脑时只有代码跟着 git 走，权重和 venv 都不进版本库，所以「跑起来需要什么」
必须写成机器可读的清单。从这一版起清单按环境拆开：

    envs/index.json         公共部分（Python 版本、镜像、下载参数）+ 环境注册表
    envs/qwen/env.json      千问：依赖包 + envs/qwen/models 权重
    envs/moss/env.json      Moss：websocket-client + envs/moss/models 权重
    envs/h3/env.json        H3：可选，envs/h3/models 权重

好处是「装了哪个环境就扩展哪块功能」：体检、补全、界面分区全按 env 字段走，
新增一个模型只要加一个 envs/<id>/ 目录和一条注册表，不用改体检代码。

Moss 与 H3 共用一份 ComfyUI 运行时（comfyui/ 与它的 .venv 都不复制），
权重各自放在 envs/<id>/models，由生成的 comfyui/extra_model_paths.yaml 指过去。
"""
import json
import os
import shutil

INDEX = "envs/index.json"
ENVS_DIR = "envs"
BASE = "base"

# ComfyUI 认的权重子目录。生成 extra_model_paths.yaml 时逐个列出来，
# 因为 ComfyUI 只扫描配置文件里点名的那几个文件夹。
COMFY_FOLDERS = (
    "checkpoints", "clip", "clip_vision", "configs", "controlnet", "diffusers",
    "diffusion_models", "embeddings", "gligen", "hypernetworks", "loras",
    "model_patches", "photomaker", "style_models", "text_encoders", "unet",
    "upscale_models", "vae", "vae_approx", "audio_encoders",
    "background_removal", "detection", "frame_interpolation",
    "geometry_estimation", "latent_upscale_models", "optical_flow",
)

YAML_MARK = "# generated by imgTools"


class SpecError(Exception):
    """envs/index.json 或某个环境清单读不了、不成形。"""


def _read_json(path, label):
    try:
        with open(path, "r", encoding="utf-8") as f:
            data = json.load(f)
    except OSError as e:
        raise SpecError("读不到 %s：%s" % (label, e))
    except ValueError as e:
        raise SpecError("%s 不是合法 JSON：%s" % (label, e))
    if not isinstance(data, dict):
        raise SpecError("%s 顶层必须是对象" % label)
    return data


def index_path(root):
    return os.path.join(root, *INDEX.split("/"))


def load_spec(root):
    """读注册表并把各环境清单合并成一份体检用的 spec。

    合并后的形状与老单文件清单一致（python/indexes/download/packages/models/dirs），
    只是每一项多一个 env 字段；另外多出 envs（注册表）与 runtimes（共用运行时）。
    """
    idx = _read_json(index_path(root), INDEX)
    merged = {
        "python": idx.get("python") or {},
        "indexes": idx.get("indexes") or {},
        "download": idx.get("download") or {},
        "runtimes": idx.get("runtimes") or {},
        "packages": [],
        "models": [],
        "dirs": [],
        "envs": [],
        "spec": INDEX,
    }
    for p in idx.get("packages") or []:
        q = dict(p)
        q.setdefault("env", BASE)
        merged["packages"].append(q)
    for d in idx.get("dirs") or []:
        q = dict(d)
        q.setdefault("env", BASE)
        merged["dirs"].append(q)

    for e in idx.get("envs") or []:
        eid = str(e.get("id") or "")
        if not eid:
            raise SpecError("%s 里有环境没写 id" % INDEX)
        rel = str(e.get("spec") or (eid + "/env.json"))
        es = _read_json(os.path.join(root, ENVS_DIR, *rel.split("/")),
                        "%s/%s" % (ENVS_DIR, rel))
        meta = {
            "id": eid,
            "label": str(e.get("label") or eid),
            "icon": str(e.get("icon") or "db"),
            "engine": str(e.get("engine") or eid),
            "optional": bool(e.get("optional") or es.get("optional")),
            "runtime": str(e.get("runtime") or es.get("runtime") or ""),
            "title": str(es.get("title") or e.get("label") or eid),
            "desc": str(es.get("desc") or ""),
            "models_dir": str(es.get("models_dir") or ""),
            "spec": "%s/%s" % (ENVS_DIR, rel),
        }
        merged["envs"].append(meta)
        for key in ("packages", "models", "dirs"):
            for item in es.get(key) or []:
                q = dict(item)
                q["env"] = eid
                merged[key].append(q)

    for key in ("packages", "models"):
        if not isinstance(merged[key], list):
            raise SpecError("%s 的 %s 段必须是数组" % (INDEX, key))
    return merged


def env_meta(spec, env_id):
    for e in spec.get("envs") or []:
        if e["id"] == env_id:
            return e
    return {}


def envs_meta(spec):
    """给前端画分区用：基础上再加各环境（含图标、说明、是否可选）。"""
    out = [{"id": BASE, "label": "基础", "icon": "db", "engine": "",
            "optional": False, "title": "运行环境",
            "desc": "主 .venv、界面壳与输出目录；两个引擎都靠它。"}]
    out.extend(spec.get("envs") or [])
    return out


def envs_of_engine(spec, engine):
    """控制台模式过滤：qwen 只看千问，moss 看 Moss 与依赖同一运行时的 H3。"""
    if engine not in ("qwen", "moss"):
        return {e["id"] for e in spec.get("envs") or []} | {BASE}
    ids = {e["id"] for e in spec.get("envs") or [] if e.get("engine") == engine}
    return ids | {BASE}


def _abs(root, rel):
    return os.path.join(root, *str(rel).split("/"))


def env_models_dir(root, spec, env_id):
    meta = env_meta(spec, env_id)
    rel = meta.get("models_dir") or ("%s/models" % env_id)
    return _abs(root, os.path.join(ENVS_DIR, *rel.split("/")))


def model_dir(root, model):
    """清单里模型条目的 dir 相对项目根；返回绝对路径。"""
    return _abs(root, model.get("dir") or "")


def runtime_dir(root, spec, name="comfyui"):
    rt = (spec.get("runtimes") or {}).get(name) or {}
    return _abs(root, rt.get("dir") or "comfyui")


def env_installed(root, spec, env_id):
    """这个环境装没装：至少有一个 must 文件在盘上就算装了。"""
    meta = env_meta(spec, env_id)
    models = [m for m in spec.get("models") or [] if m.get("env") == env_id]
    if not models:
        return False
    for m in models:
        base = model_dir(root, m)
        for rel in (m.get("must") or {}):
            if os.path.isfile(os.path.join(base, *str(rel).split("/"))):
                return True
    return False


# ---------------------------------------------------------------- ComfyUI 权重路径
def extra_model_paths_text(root, spec):
    """生成 comfyui/extra_model_paths.yaml：每个环境的权重目录各占一节。"""
    lines = [YAML_MARK, "# 各环境的权重目录（体检/补全会重写本文件）"]
    any_env = False
    for e in spec.get("envs") or []:
        if e.get("runtime") != "comfyui":
            continue
        base = env_models_dir(root, spec, e["id"])
        lines.append("%s:" % e["id"].replace("-", "_"))
        lines.append("  base_path: %s" % json.dumps(base.replace("\\", "/")))
        for folder in COMFY_FOLDERS:
            lines.append("  %s: %s" % (folder, folder))
        any_env = True
    if not any_env:
        return ""
    return "\n".join(lines) + "\n"


def write_extra_model_paths(root, spec, log=None):
    """把权重目录写进 ComfyUI；返回写好的相对路径（没运行时返回空串）。"""
    text = extra_model_paths_text(root, spec)
    if not text:
        return ""
    rt = (spec.get("runtimes") or {}).get("comfyui") or {}
    path = os.path.join(runtime_dir(root, spec), "extra_model_paths.yaml")
    if not os.path.isdir(os.path.dirname(path)):
        return ""
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as f:
            old = f.read()
    except OSError:
        old = ""
    if old.strip() and YAML_MARK not in old:
        bak = path + ".user.bak"
        if not os.path.exists(bak):
            try:
                shutil.copyfile(path, bak)
                if log:
                    log("📝 原来的 extra_model_paths.yaml 已备份为 %s" % os.path.basename(bak))
            except OSError:
                pass
    if old == text:
        return os.path.relpath(path, root)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    os.replace(tmp, path)
    if log:
        log("🗂️ 已更新 ComfyUI 权重路径：%s" % os.path.relpath(path, root))
    return os.path.relpath(path, root)


# ---------------------------------------------------------------- 旧布局迁移
def _move_children(src, dst, log=None, dry_run=False, actions=None):
    """把 src 下的内容逐个搬到 dst（同盘 move 是改名，15GB 也是一瞬间）。

    目标已存在就跳过并记一笔，不覆盖用户已有的东西；跨盘/被占用时回落 copy。
    """
    actions = actions if actions is not None else []
    if not os.path.isdir(src):
        return actions
    os.makedirs(dst, exist_ok=True)
    for name in sorted(os.listdir(src)):
        if name.startswith("."):
            continue
        s, d = os.path.join(src, name), os.path.join(dst, name)
        if os.path.exists(d):
            actions.append("跳过（目标已存在）%s" % os.path.relpath(d))
            continue
        if dry_run:
            actions.append("会移动 %s → %s" % (s, d))
            continue
        try:
            shutil.move(s, d)
            actions.append("移动 %s → %s" % (s, d))
            if log:
                log("📦 %s → %s" % (s, d))
        except OSError as e:
            actions.append("移动失败 %s：%s" % (s, e))
    return actions


def migrate_layout(root, spec=None, dry_run=False, log=None):
    """把旧布局（根 models/、comfyui/models）迁到 envs/<id>/models。

    幂等：目标已存在的条目一律不动，重复跑只会打印「跳过」。
    """
    spec = spec or load_spec(root)
    actions = []
    legacy_qwen = os.path.join(root, "models")
    if os.path.isdir(legacy_qwen):
        actions = _move_children(legacy_qwen, env_models_dir(root, spec, "qwen"),
                                 log, dry_run, actions)
        if not dry_run:
            try:
                if not os.listdir(legacy_qwen):
                    os.rmdir(legacy_qwen)
            except OSError:
                pass
    if env_meta(spec, "moss"):
        legacy_moss = os.path.join(runtime_dir(root, spec), "models")
        actions = _move_children(legacy_moss,
                                 env_models_dir(root, spec, "moss"),
                                 log, dry_run, actions)
    return actions


def migrate_cfg_paths(root, cfg):
    """配置里的旧路径换成新目录；只在新目录确实存在时改，避免把人指丢。"""
    c = cfg.get("console") or {}
    old = str(c.get("model_dir") or "")
    if old.startswith("models/"):
        new = "envs/qwen/models/" + old[len("models/"):]
        old_abs = _abs(root, old)
        new_abs = _abs(root, new)
        if not os.path.isdir(old_abs) or os.path.isdir(new_abs):
            c["model_dir"] = new
    return cfg.get("console") or {}
