/* 点一张卡片的动作。promptKey 形如 gen.prompt / moss.prompt：
   - 反向那一类填进同块的 negative 框（用户自己写过的，词库页里也允许覆盖，那是明确点「填入反向」）
   - 分类带 add（光影）时拼在现有句子后面，整句那一类直接换掉整句
   - 反向框原本空着时，顺手补上这条/这一类的通用反向 */
function fill(promptKey,item,cat){
  const C=MIC.form;
  const negKey=promptKey.replace(/\.prompt$/,'.negative');
  if(cat.id==='negative'){
    C.commitPath(negKey,item.pos);
    MIC.toast('已填入反向：'+item.name);
    return;
  }
  const cur=String(MIC.mget(MIC.s.cfg,promptKey)||'').trim();
  const add=!!(cat.add||item.add);
  C.commitPath(promptKey,add&&cur?cur+'，'+item.pos:item.pos);
  if(!String(MIC.mget(MIC.s.cfg,negKey)||'').trim())
    C.commitPath(negKey,item.neg||cat.neg||NEG_BASE);
  MIC.toast((add?'已追加：':'已填入：')+item.name);
}

